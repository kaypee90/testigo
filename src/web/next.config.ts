import type { NextConfig } from "next";

// Sent with every page. Pages may only be framed by the dashboard itself (file previews and split
// views). The staff dashboard loads no third-party code (NFR-SEC-2 applies in full to the separate
// reporter app, src/Testigo.Reporter).
const securityHeaders = [
  { key: "X-Frame-Options", value: "SAMEORIGIN" },
  { key: "Content-Security-Policy", value: "frame-ancestors 'self'" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "no-referrer" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
];

const nextConfig: NextConfig = {
  output: "standalone",
  poweredByHeader: false,
  // Keep the dev badge clear of the sidebar's account card.
  devIndicators: { position: "bottom-right" },
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
};

export default nextConfig;
